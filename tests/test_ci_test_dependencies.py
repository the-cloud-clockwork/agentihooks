@pytest.mark.feature("ci-tool-constraint-files")
def test_the_ci_tool_generator_writes_each_checked_in_file(tmp_path: Path) -> None:
    calls = tmp_path / "calls"
    calls.mkdir()
    stub = tmp_path / "bin" / "uv"
    stub.parent.mkdir()
    stub.write_text(f'#!/usr/bin/env bash\nprintf "%s\\0" "$@" > "{calls}/$$.argv"\ncat > "{calls}/$$.stdin"\n')
    stub.chmod(0o755)
    env = {**os.environ, "PATH": f"{stub.parent}{os.pathsep}{os.environ['PATH']}"}
    subprocess.run(["bash", str(ROOT / CI_TOOLS_GENERATOR)], cwd=tmp_path, env=env, check=True)
    written: dict[str, list[Requirement]] = {}
    for record in sorted(calls.glob("*.argv")):
        argv = record.read_text().split("\0")[:-1]
        assert argv[:3] == ["pip", "compile", "-"] and {"--upgrade", "--exclude-newer"} <= set(argv), argv
        roots = record.with_suffix(".stdin").read_text().split()
        written[argv[argv.index("--output-file") + 1]] = [Requirement(root) for root in roots]
    assert sorted(written) == sorted(f"{CI_TOOLS}/{path.name}" for path in (ROOT / CI_TOOLS).iterdir())
    for output, roots in written.items():
        pins = [Requirement(line) for line in (ROOT / output).read_text().splitlines()[2:]]
        for root in roots:
            versions = [
                next(iter(pin.specifier)).version
                for pin in pins
                if canonicalize_name(pin.name) == canonicalize_name(root.name)
            ]
            assert versions and all(root.specifier.contains(version) for version in versions), (output, str(root))


